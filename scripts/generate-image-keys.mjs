/**
 * Writes the list of photographs a country site is allowed to replace.
 *
 *   npm run generate-image-keys
 *
 * The site's wording has been changeable per country for a while: Page wording
 * derives its list from messages/en.json, so every string on the site is
 * offered without anyone maintaining a second copy of it. The photographs had
 * no equivalent — they are `src="/images/…"` written into the components, and
 * a country wanting its own picture of its own students had no way to say so.
 *
 * There is no en.json for images, so this makes one: it reads the components,
 * collects every path under /images they draw, and records where each is used
 * so the admin can offer "the banner on Who We Are" rather than a filename.
 *
 * Generated rather than hand-listed for the same reason the wording list is
 * derived: a photograph added to a page becomes replaceable the moment this is
 * re-run, and one deleted stops being offered.
 *
 * Re-run it after adding or removing an image. Nothing breaks if you forget —
 * the new photograph is simply not offered yet.
 */

import fs from "node:fs";
import path from "node:path";

const ROOT = path.join(import.meta.dirname, "..");
const SRC = path.join(ROOT, "src");
const OUT = path.join(SRC, "lib", "siteImages.ts");

/** Every .ts/.tsx file under src. */
function sources(dir, found = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) sources(full, found);
    else if (/\.tsx?$/.test(entry.name)) found.push(full);
  }
  return found;
}

/**
 * A readable name for the place an image is drawn.
 *
 * A route file is named by its address, which is what an editor recognises; a
 * component by its own name. Anything else falls back to its path.
 */
function where(file) {
  const rel = path.relative(SRC, file).replaceAll(path.sep, "/");

  const route = /^app\/\(frontend\)\/\[locale\]\/(.*)\/page\.tsx$/.exec(rel);
  if (route) return `/${route[1]}`;
  if (rel === "app/(frontend)/[locale]/page.tsx") return "/ (home page)";

  const component = /([A-Za-z0-9_]+)\.tsx?$/.exec(rel);
  return component ? component[1] : rel;
}

const used = new Map();
for (const file of sources(SRC)) {
  const text = fs.readFileSync(file, "utf8");
  for (const [, image] of text.matchAll(/["'](\/images\/[A-Za-z0-9._-]+)["']/g)) {
    if (!used.has(image)) used.set(image, new Set());
    used.get(image).add(where(file));
  }
}

const rows = [...used.entries()]
  .map(([image, places]) => ({ path: image, usedOn: [...places].sort() }))
  .sort((a, b) => a.path.localeCompare(b.path));

// A path that names no file is not a photograph anyone can replace. Usually
// it came out of an example in a doc comment, which is why this scans for a
// file on disk rather than trusting the string.
const missing = rows.filter((row) => !fs.existsSync(path.join(ROOT, "public", row.path)));
const present = rows.filter((row) => fs.existsSync(path.join(ROOT, "public", row.path)));
if (missing.length) {
  console.warn(
    `Skipped ${missing.length} path(s) with no file in public/images: ` +
      missing.map((row) => row.path).join(", "),
  );
}

const file = `// Generated by scripts/generate-image-keys.mjs. Do not edit by hand.
//
// Every photograph the site draws from /images, and where it is drawn. This is
// to pictures what messages/en.json is to wording: the list of what a country
// site may replace with its own. Read by the Page wording collection, which
// offers these, and by components/ui/SiteImage, which swaps in whatever a
// country chose.
//
// Re-run \`npm run generate-image-keys\` after adding or removing an image.

export type SiteImage = {
  /** The path as the components write it, e.g. "/images/about-hero.webp". */
  path: string;
  /** The pages and components that draw it, for the label in the admin. */
  usedOn: string[];
};

export const SITE_IMAGES: SiteImage[] = ${JSON.stringify(present, null, 2)};

/** Reverse lookup, for resolving a path at render time. */
export const SITE_IMAGE_PATHS: ReadonlySet<string> = new Set(
  SITE_IMAGES.map((image) => image.path),
);
`;

fs.writeFileSync(OUT, file);
console.log(
  `${present.length} images written to ${path.relative(ROOT, OUT)}, ` +
    `used across ${new Set([...used.values()].flatMap((set) => [...set])).size} pages and components.`,
);
