/**
 * Precomputes the dot-matrix world map used by the network map.
 *
 * Doing this at build time keeps d3-geo, topojson-client and world-atlas out
 * of the browser bundle entirely — the client only ships a flat array of
 * coordinates.
 *
 * Run with:  node scripts/generate-world-dots.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { geoEquirectangular, geoContains } from "d3-geo";
import { feature } from "topojson-client";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

// Viewbox the map component draws into.
const WIDTH = 1000;
const HEIGHT = 500;
// Spacing between dots, in viewbox units. Smaller = denser map.
const STEP = 5.5;
// Equirectangular badly exaggerates the poles, and the design shows no
// Antarctica, so the map is cropped to the inhabited band.
const MAX_LAT = 80;
const MIN_LAT = -56;

const topo = JSON.parse(
  readFileSync(resolve(root, "node_modules/world-atlas/land-110m.json"), "utf8"),
);
const land = feature(topo, topo.objects.land);

// Rotated so the Americas sit centre-frame with Asia to the left and
// Europe/Africa to the right, matching the design's framing.
const projection = geoEquirectangular()
  .rotate([100, 0])
  .fitSize([WIDTH, HEIGHT], { type: "Sphere" });

const dots = [];
for (let y = STEP / 2; y < HEIGHT; y += STEP) {
  for (let x = STEP / 2; x < WIDTH; x += STEP) {
    const lonLat = projection.invert([x, y]);
    if (!lonLat) continue;
    if (lonLat[1] > MAX_LAT || lonLat[1] < MIN_LAT) continue;
    if (!geoContains(land, lonLat)) continue;
    dots.push([Math.round(x * 10) / 10, Math.round(y * 10) / 10]);
  }
}

// Viewbox crop matching the latitude clip above.
const MIN_Y = Math.round(((90 - MAX_LAT) / 180) * HEIGHT);
const CROP_H = Math.round(((90 - MIN_LAT) / 180) * HEIGHT) - MIN_Y;

mkdirSync(resolve(root, "src/lib"), { recursive: true });
writeFileSync(
  resolve(root, "src/lib/worldDots.ts"),
  `// GENERATED by scripts/generate-world-dots.mjs — do not edit by hand.\n` +
    `// Land dots for a ${WIDTH}x${HEIGHT} equirectangular viewbox rotated to [100, 0].\n` +
    `export const WORLD_VIEWBOX = { width: ${WIDTH}, height: ${HEIGHT}, minY: ${MIN_Y}, cropHeight: ${CROP_H} } as const;\n` +
    `export const WORLD_DOTS: readonly (readonly [number, number])[] = ${JSON.stringify(dots)};\n`,
  "utf8",
);

console.log(`wrote ${dots.length} dots to src/lib/worldDots.ts`);
