/**
 * Precomputes the point cloud the network globe is drawn from: one dot per
 * cell of an equal-area grid that falls on land.
 *
 * Same bargain as scripts/generate-map-views.mjs — d3-geo, topojson-client and
 * world-atlas stay out of the browser bundle, and the client ships a packed
 * array of numbers it can project with plain trigonometry.
 *
 * The grid steps in latitude and then divides each latitude band into as many
 * longitude steps as that band's circumference can hold, so the dots stay
 * evenly spaced on the sphere instead of bunching at the poles the way a
 * naive lat/lng grid does.
 *
 * Run with:  node scripts/generate-globe-points.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

/** Degrees between latitude rows. Smaller is denser and a larger file. */
const STEP = 0.9;
/** Antarctica is a band of noise at this size; the map views clip it too. */
const SOUTH_LIMIT = -58;
const NORTH_LIMIT = 84;

const topology = JSON.parse(
  readFileSync(resolve(root, "node_modules/world-atlas/land-50m.json"), "utf8"),
);
const land = feature(topology, topology.objects.land);

const points = [];
for (let lat = SOUTH_LIMIT; lat <= NORTH_LIMIT; lat += STEP) {
  const circumference = Math.cos((lat * Math.PI) / 180);
  const columns = Math.max(1, Math.round((360 / STEP) * circumference));
  for (let column = 0; column < columns; column++) {
    const lng = -180 + (360 * column) / columns;
    if (geoContains(land, [lng, lat])) points.push([lat, lng]);
  }
}

/**
 * Packed as two flat arrays of tenths-of-a-degree integers rather than an
 * array of pairs: it is a third of the bytes, and the client reads it in one
 * pass anyway.
 */
const lats = points.map(([lat]) => Math.round(lat * 10));
const lngs = points.map(([, lng]) => Math.round(lng * 10));

const out = `// GENERATED by scripts/generate-globe-points.mjs — do not edit by hand.

/** Land points, in tenths of a degree. Paired by index with LAND_LNG. */
export const LAND_LAT = [${lats.join(",")}] as const;

/** Land points, in tenths of a degree. Paired by index with LAND_LAT. */
export const LAND_LNG = [${lngs.join(",")}] as const;
`;

mkdirSync(resolve(root, "src/lib"), { recursive: true });
writeFileSync(resolve(root, "src/lib/globePoints.ts"), out);

console.log(
  `${points.length} land points at ${STEP}° — ${(Buffer.byteLength(out) / 1024).toFixed(0)}KB`,
);
